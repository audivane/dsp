// Regenerate src/api/generated from crates/protocol (ts-rs, feature `ts`).
// Usage: npm run gen:types
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, rmSync, mkdirSync, copyFileSync, writeFileSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(here, "../..");
const out = resolve(here, "../src/api/generated");
const tmp = mkdtempSync(join(tmpdir(), "avdsp-ts-"));

execFileSync(
  "cargo",
  ["test", "-q", "-p", "audivane-protocol", "--features", "ts", "export_bindings"],
  { cwd: workspace, stdio: "inherit", env: { ...process.env, TS_RS_EXPORT_DIR: tmp } },
);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const names = [];
function copyTree(src, dst) {
  for (const entry of readdirSync(src).sort()) {
    const s = join(src, entry);
    const d = join(dst, entry);
    if (statSync(s).isDirectory()) {
      mkdirSync(d, { recursive: true });
      copyTree(s, d);
    } else if (entry.endsWith(".ts")) {
      copyFileSync(s, d);
      if (src === tmp) names.push(entry.slice(0, -3));
    }
  }
}
copyTree(tmp, out);
rmSync(tmp, { recursive: true, force: true });
writeFileSync(
  join(out, "index.ts"),
  "// Generated by scripts/gen-types.mjs from crates/protocol. Do not edit.\n" +
    names.map((n) => `export type { ${n} } from "./${n}";\n`).join(""),
);
console.log(`wrote ${names.length} types to ${out}`);
